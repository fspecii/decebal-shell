#!/usr/bin/env python3
"""Private filesystem regressions for source-managed asset retirement."""
import importlib.util
import json
import os
from pathlib import Path
import stat
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

SPEC = importlib.util.spec_from_file_location('retirement', Path(__file__).resolve().parents[1] / 'tools/retire-generated-assets.py')
M = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(M)


class RetirementTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='asset-retirement-test-')
        self.addCleanup(self.temp.cleanup)
        base = Path(self.temp.name)
        self.repo, self.themes, self.backup = base/'source', base/'installed', base/'backup'
        for p in [self.repo/'docs', self.repo/'themes/demo', self.themes/'demo/wallpapers']:
            p.mkdir(parents=True)
        self.old = b'name="Demo"\n[wallpaper]\nimage="wallpapers/old.png"\n'
        self.new = b'name="Demo"\n'
        (self.repo/'themes/demo/theme.toml').write_bytes(self.new)
        (self.themes/'demo/theme.toml').write_bytes(self.old)
        self.asset = self.themes/'demo/wallpapers/old.png'
        self.asset.write_bytes(b'known generated bytes')
        (self.themes/'demo/user-note.txt').write_text('keep unknown user file')
        audit = {'format':1,'baseline_commit':'abcdef', 'themes':[{'theme_id':'demo','removed':[{'path':'themes/demo/wallpapers/old.png','sha256':M.digest(self.asset.read_bytes()),'bytes':self.asset.stat().st_size}]}]}
        (self.repo/'docs/generated-wallpaper-removal.json').write_text(json.dumps(audit))
        self.known = patch.object(M, 'known_manifests', return_value={self.old,self.new})
        self.known.start()
        self.addCleanup(self.known.stop)

    def run_tool(self, **kwargs):
        return M.retire(self.repo,self.themes,self.backup,**kwargs)

    def test_default_dry_run_never_creates_backups_or_changes_files(self):
        result=self.run_tool()
        self.assertEqual(len(result['planned']),2)
        self.assertFalse(self.backup.exists())
        self.assertEqual((self.themes/'demo/theme.toml').read_bytes(),self.old)
        self.assertTrue(self.asset.exists())

    def test_known_manifest_and_exact_asset_are_backed_up_then_retired(self):
        result=self.run_tool(apply=True)
        self.assertEqual(len(result['changed']),2)
        self.assertEqual((self.themes/'demo/theme.toml').read_bytes(),self.new)
        self.assertFalse(self.asset.exists())
        self.assertEqual((self.backup/'demo/theme.toml').read_bytes(),self.old)
        self.assertEqual((self.backup/'demo/wallpapers/old.png').read_bytes(),b'known generated bytes')
        self.assertEqual(stat.S_IMODE(self.backup.stat().st_mode),0o700)
        self.assertEqual(stat.S_IMODE((self.backup/'demo/theme.toml').stat().st_mode),0o600)
        self.assertTrue((self.themes/'demo/user-note.txt').exists())

    def test_hidden_alias_audit_uses_its_baseline_and_skips_source_docs(self):
        path=self.repo/'docs/generated-wallpaper-removal.json';audit=json.loads(path.read_text())
        record=audit['themes'][0];record['baseline_commit']='401ebc9'
        record['removed'].append({'path':'docs/themes/demo.png','sha256':'0'*64,'bytes':42})
        source_note=self.repo/'docs/source-note.txt';source_note.write_text('source untouched')
        path.write_text(json.dumps(audit))
        result=self.run_tool(apply=True)
        self.assertEqual(len(result['changed']),2)
        M.known_manifests.assert_called_with(self.repo,'demo','401ebc9')
        self.assertEqual(source_note.read_text(),'source untouched')

    def test_modified_manifest_preserves_entire_package(self):
        custom=self.old+b'# custom preference\n'
        (self.themes/'demo/theme.toml').write_bytes(custom)
        result=self.run_tool(apply=True)
        self.assertFalse(result['changed'])
        self.assertFalse(self.backup.exists())
        self.assertTrue(self.asset.exists())
        self.assertEqual((self.themes/'demo/theme.toml').read_bytes(),custom)

    def test_modified_asset_survives_manifest_update(self):
        self.asset.write_bytes(b'my own changed artwork')
        result=self.run_tool(apply=True)
        self.assertEqual(result['changed'],['demo/theme.toml'])
        self.assertEqual(self.asset.read_bytes(),b'my own changed artwork')

    def test_protected_selected_asset_is_retained(self):
        result=self.run_tool(apply=True,keep_paths=[self.asset])
        self.assertEqual(result['changed'],['demo/theme.toml'])
        self.assertTrue(self.asset.exists())
        self.assertIn('referenced/protected file',[x['reason'] for x in result['skipped']])

    def test_symlink_asset_and_parent_directory_never_follow_outside(self):
        outside=Path(self.temp.name)/'outside.png';outside.write_bytes(self.asset.read_bytes())
        self.asset.unlink();self.asset.symlink_to(outside)
        with self.assertRaises(M.RetirementError):self.run_tool(apply=True)
        self.assertFalse(self.backup.exists())
        self.assertEqual(outside.read_bytes(),b'known generated bytes')
        self.asset.unlink();self.asset.parent.rmdir();self.asset.parent.symlink_to(outside.parent)
        with self.assertRaises(M.RetirementError):self.run_tool(apply=True)
        self.assertFalse(self.backup.exists())

    def test_manifest_link_root_escape_and_existing_backup_are_rejected(self):
        outside=Path(self.temp.name)/'original.toml';outside.write_bytes(self.old)
        (self.themes/'demo/theme.toml').unlink();(self.themes/'demo/theme.toml').symlink_to(outside)
        with self.assertRaises(M.RetirementError):self.run_tool(apply=True)
        self.assertEqual(outside.read_bytes(),self.old)
        with self.assertRaises((M.RetirementError,OSError)):M.retire(self.repo,Path('/usr'),self.backup,apply=True)
        self.backup.mkdir()
        with self.assertRaises(M.RetirementError):self.run_tool(apply=True)

    def test_audit_traversal_is_rejected_before_writes(self):
        path=self.repo/'docs/generated-wallpaper-removal.json';audit=json.loads(path.read_text())
        audit['themes'][0]['removed'][0]['path']='themes/demo/../../outside.png';path.write_text(json.dumps(audit))
        with self.assertRaises(M.RetirementError):self.run_tool(apply=True)
        self.assertFalse(self.backup.exists())

    def test_cli_uses_raw_private_git_history_and_is_dry_by_default(self):
        self.known.stop()
        env = dict(os.environ, GIT_CONFIG_NOSYSTEM='1', GIT_CONFIG_GLOBAL='/dev/null')
        def git(*args):
            return subprocess.run(['git', '-c', 'core.hooksPath=/dev/null', '-c', 'user.name=Fixture', '-c', 'user.email=fixture@example.invalid', '-C', str(self.repo), *args], env=env, capture_output=True, check=True).stdout.decode().strip()
        git('init', '-q')
        (self.repo/'themes/demo/theme.toml').write_bytes(self.old)
        git('add', '.')
        git('commit', '-qm', 'old source fixture')
        old = git('rev-parse', 'HEAD')
        audit_path=self.repo/'docs/generated-wallpaper-removal.json'
        audit=json.loads(audit_path.read_text());audit['baseline_commit']=old;audit_path.write_text(json.dumps(audit))
        (self.repo/'themes/demo/theme.toml').write_bytes(self.new)
        git('add', '.');git('commit', '-qm', 'new source fixture')
        command=[sys.executable,str(Path(M.__file__)), '--repo',str(self.repo),'--themes-dir',str(self.themes),'--backup-dir',str(self.backup)]
        result=subprocess.run(command,env=env,capture_output=True,text=True,check=True)
        self.assertFalse(json.loads(result.stdout)['apply'])
        self.assertEqual(len(json.loads(result.stdout)['planned']),2)
        self.assertFalse(self.backup.exists())
        subprocess.run(command+['--apply'],env=env,capture_output=True,text=True,check=True)
        self.assertFalse(self.asset.exists())
        self.assertEqual((self.backup/'demo/theme.toml').read_bytes(),self.old)

    def test_backup_failure_never_mutates_installed_files(self):
        with patch.object(M,'private_write',side_effect=OSError('backup disk full')):
            with self.assertRaises(M.RetirementError) as got:self.run_tool(apply=True)
        self.assertIn('installed files untouched',got.exception.report['phase'])
        self.assertEqual((self.themes/'demo/theme.toml').read_bytes(),self.old)
        self.assertTrue(self.asset.exists())

    def test_failed_delete_rolls_manifest_back_and_keeps_all_originals(self):
        with patch.object(M,'remove',side_effect=OSError('injected failure')):
            with self.assertRaises(M.RetirementError) as got:self.run_tool(apply=True)
        self.assertTrue(got.exception.report['rolled_back'])
        self.assertEqual((self.themes/'demo/theme.toml').read_bytes(),self.old)
        self.assertTrue(self.asset.exists())

    def test_failed_rollback_is_explicit_and_backup_remains_recoverable(self):
        real=M.replace;calls=[]
        def fail_rollback(*args):
            calls.append(args)
            if len(calls)>1:raise OSError('rollback denied')
            return real(*args)
        with patch.object(M,'remove',side_effect=OSError('delete denied')),patch.object(M,'replace',side_effect=fail_rollback):
            with self.assertRaises(M.RetirementError) as got:self.run_tool(apply=True)
        self.assertFalse(got.exception.report['rolled_back'])
        self.assertEqual(len(got.exception.report['rollback_errors']),1)
        self.assertEqual((self.backup/'demo/theme.toml').read_bytes(),self.old)
        self.assertTrue(self.asset.exists())
        self.assertFalse(json.loads((self.backup/'result.json').read_text())['rolled_back'])


if __name__=='__main__':unittest.main()
