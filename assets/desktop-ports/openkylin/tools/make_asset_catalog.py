#!/usr/bin/env python3
"""Write assets/desktop-ports/openkylin/asset-packs.toml (the shared decebal asset-pack catalogue) from the local upstream clones.

Usage: python3 -I make_asset_catalog.py UPSTREAM_DIR OUT_TOML
Data only: read-only git queries (rev-parse) and `cursors.sh` read as text. Nothing is fetched, built or installed here: the shared
installer (`decthemectl assets install`, src/desktop_assets) verifies the pinned tree ids and builds the cursors natively.
"""
import importlib.util, pathlib, subprocess, sys

here = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("cursor_table", here / "cursor_table.py"); ct = importlib.util.module_from_spec(spec); spec.loader.exec_module(ct)
up = pathlib.Path(sys.argv[1]).expanduser()
def git(repo, *a): return subprocess.run(["git", "-C", str(up / repo), *a], check=True, capture_output=True, text=True).stdout.strip()

theme_commit = git("openkylin-theme", "rev-parse", "HEAD"); dmz_commit = git("dmz-cursor-theme", "rev-parse", "HEAD")
# the licence texts the repositories actually carry (neither has a LICENSE/COPYING at its root): debian/copyright, pinned by blob id
theme_lic = git("openkylin-theme", "rev-parse", "HEAD:debian/copyright"); dmz_lic = git("dmz-cursor-theme", "rev-parse", "HEAD:debian/copyright")
tree = lambda repo, path: git(repo, "rev-parse", f"HEAD:{path}")
# the cursor hotspot tables come from the pinned commit's own script text
script = lambda path: subprocess.run(["git", "-C", str(up / "openkylin-theme"), "show", f"HEAD:{path}/cursors.sh"], check=True, capture_output=True, text=True).stdout

out = f'''# Companion asset-pack catalogue for the openKylin (UKUI) port. Format and rules: docs/desktop-asset-packs.md (shared installer).
# Data only. Generated by assets/desktop-ports/openkylin/tools/make_asset_catalog.py from read-only `git rev-parse` queries on the pinned
# clones (GitHub mirror of openkylin, April 2025; the same trees as gitee.com/openkylin). Nothing in this file is executed.
#
# Cursors: dark-sense / blue-crystal are PNGs whose hotspots live in an upstream shell script (`cursors.sh`). The tables below were read from
# that script's text (never run) at the pinned commit; the installer builds the Xcursor files natively and installs neither the PNGs nor the
# script. The `aliases` also include CSS cursor-spec names (default, pointer, text, wait, not-allowed, ...) that the upstream themes lack;
# they are additive and never replace an upstream file.
#
# Licences: openkylin-theme debian/copyright DECLARES GPL-3 for all files ("either version 3"); that is a declaration, not a verification. The three icon
# packs' index.theme says `Comment=Icon theme for UKUI ,from moka.`: part of the artwork may descend from the Moka icon theme, and its terms, and
# whether this repository may relicense it, are UNRESOLVED (not researched, not assumed). DMZ: CC-BY-SA-3.0 for the theme (Novell, 2007-2010),
# GPL-2+ for its renderpngs.py (not used). `license_oids` pin the exact debian/copyright blobs that were read.
format = 1
family = "openkylin"

[[source]]
id = "openkylin-theme"
repo = "https://github.com/openkylin/openkylin-theme"
revision = "openkylin/nile"
commit = "{theme_commit}"
license = "GPL-3.0-only"
license_files = ["debian/copyright"]
license_oids = ["{theme_lic}"]
archive_url = "https://github.com/openkylin/openkylin-theme/archive/{theme_commit}.tar.gz"
strip_components = 1

[[source]]
id = "dmz-cursor-theme"
repo = "https://github.com/openkylin/dmz-cursor-theme"
revision = "openkylin/yangtze"
commit = "{dmz_commit}"
license = "CC-BY-SA-3.0"
license_files = ["debian/copyright"]
license_oids = ["{dmz_lic}"]
archive_url = "https://github.com/openkylin/dmz-cursor-theme/archive/{dmz_commit}.tar.gz"
strip_components = 1

'''
for pid, name, path, desc in [
    ("openkylin-ukui-default", "UKUI Default (光)", "icons/ukui-icon-theme-default", "UKUI's default icon pack: v11 and Light-Seeking. Fashion and Classical inherit from it. Licence declared GPL-3 by debian/copyright; part of the artwork says `from moka`: provenance unresolved."),
    ("openkylin-ukui-classical", "UKUI Classical (典)", "icons/ukui-icon-theme-classical", "UKUI's classical icon pack (Classic global theme). Inherits ukui-icon-theme-default: install both for full coverage. Moka-derived provenance unresolved."),
    ("openkylin-ukui-fashion", "UKUI Fashion (印)", "icons/ukui-icon-theme-fashion", "UKUI's fashion icon pack (HeYin global theme). Inherits ukui-icon-theme-default: install both for full coverage. Moka-derived provenance unresolved."),
]:
    out += f'[[pack]]\nid = "{pid}"\nname = "{name}"\nprovides = ["icons"]\nsource = "openkylin-theme"\npath = "{path}"\ntree = "{tree("openkylin-theme", path)}"\ndescription = "{desc}"\n\n'
for pid, name, path, desc in [
    ("openkylin-dark-sense", "Dark Sense (耀黑)", "icons/cursors/dark-sense", "UKUI's dark cursor theme (v11, Light-Seeking, Classic)."),
    ("openkylin-blue-crystal", "Blue Crystal", "icons/cursors/blue-crystal", "UKUI's blue cursor theme (not suggested by a shipped global theme)."),
]:
    tables, n, a = ct.toml_tables(script(path))
    out += f'[[pack]]\nid = "{pid}"\nname = "{name}"\nprovides = ["cursors"]\nsource = "openkylin-theme"\npath = "{path}"\ntree = "{tree("openkylin-theme", path)}"\ndescription = "{desc} {n} cursors, {a} alias links."\n\n{tables}\n'
out += f'''[[pack]]
id = "openkylin-dmz-white"
name = "DMZ White"
provides = ["cursors"]
source = "dmz-cursor-theme"
path = "DMZ-White"
tree = "{tree("dmz-cursor-theme", "DMZ-White")}"
description = "DMZ (White) cursors, prebuilt Xcursor files; used by the HeYin global theme."

'''
for theme, icons, cur in [("openkylin", "openkylin-ukui-default", "openkylin-dark-sense"), ("openkylin-islands", "openkylin-ukui-default", "openkylin-dark-sense"),
                          ("openkylin-light-seeking", "openkylin-ukui-default", "openkylin-dark-sense"), ("openkylin-heyin", "openkylin-ukui-fashion", "openkylin-dmz-white"),
                          ("openkylin-classic", "openkylin-ukui-classical", "openkylin-dark-sense")]:
    out += f'[[recommend]]\ntheme = "{theme}"\nicons = "{icons}"\ncursors = "{cur}"\n\n'
pathlib.Path(sys.argv[2]).write_text(out.rstrip() + "\n")
print("wrote", sys.argv[2])
