#!/usr/bin/env python3
"""Write docs/desktop-ports/openkylin/native/README.md from native-checks.json (+ native-widget.json).

Usage: python3 -I native_summary.py REPO_ROOT
"""
import json, pathlib, sys

n = pathlib.Path(sys.argv[1]) / "docs/desktop-ports/openkylin/native"
d = json.loads((n / "native-checks.json").read_text()); w = json.loads((n / "native-widget.json").read_text())
rows = ["| theme | mode | scale | screen | edge | panel window (x,y,w×h) | strip thickness measured / declared×scale | panel colour measured / expected | Δ |", "|---|---|---|---|---|---|---|---|---|"]
for r in d["results"]:
    if r.get("wallpaper"): continue
    win = list(r["windows"].values())[0]
    rows.append(f"| `{r['theme']}` | {r['mode']} | {int(r['scale'] * 100)} % | {r['geometry']} | {r['edge']} | {win['x']},{win['y']},{win['w']}×{win['h']} | {str(r['taskbar_thickness']) + ' / ' + str(r['taskbar_thickness_expected']) if 'taskbar_thickness' in r else 'n/a (island bar)'} | {tuple(r['panel_pixel'])} / {tuple(r['panel_expected'])} | {r['panel_delta']} |")
text = f"""# Native captures (private Xvfb + picom xrender, no window manager)

Display safety: every case reserves an explicit display number >= 700 (no lock, no filesystem socket and no abstract socket in use), starts its own Xvfb on it, and verifies
the lock-file owner and both socket namespaces before any input; it never uses `:0`, never probes automatically and never removes a foreign socket or lock. The
captures committed here were taken before this rule (on private numbers 360-419, none of them `:0`); the harness now enforces the high range.

Generated by `assets/desktop-ports/openkylin/tools/native_summary.py` from `native-checks.json`; produced by `tests/e2e/openkylin-native.py`.
Binaries (sha256): {', '.join(f'`{k}` `{v[:12]}…`' for k, v in d['binaries'].items())}. Flat backdrop: no photograph is committed. The panel colour
is read at a real pixel of an empty stretch of the panel (or, for the island bar, the island face) and must equal the package's `bar`/`dock`
colour at its alpha over the backdrop (tolerance 4/255). Hardware applets are absent on the fixture by design; hardware-less
tray items are not drawn. The taskbar strip thickness is the package's declared `[taskbar] thickness = 48` times the scale (48/60/96 px at 100/125/200 %), asserted per case; the earlier fixed 44 px is gone with the generic `[taskbar]` keys.

Bottom-edge 1920×1080 captures are cropped to the panel strip; side, top and short-window captures are full frame.
The UKUI time widget (`widget-ukui-time-24-*.png`, white text measured by pixel count, {', '.join(str(r['widget_text_pixels']) for r in w['results'])}) is switched on the way Settings → Widgets would.

The Control Center (`controlcenter-*.png`, `decbar --control-center`, style `fluent` from the package) was opened for `openkylin`, `openkylin-heyin` and
`openkylin-classic` (square tiles at radius 0) in both modes at 100/200 %; geometry is in `native-controlcenter.json`.

{chr(10).join(rows)}
"""
(n / "README.md").write_text(text); print("wrote", n / "README.md", len(rows) - 2, "rows")
