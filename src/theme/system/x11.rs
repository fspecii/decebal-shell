//! Plain X11 clients (st, xterm, urxvt, ...): an Xresources file included from `~/.Xresources` and merged into the running X server.
//!
//! The file sets the terminal colours (`*.foreground`, `*.background`, `*.cursorColor`, `*.color0` .. `*.color15`) and, when configured,
//! `Xcursor.theme`. The include lives in a managed block of `~/.Xresources`, so a session that runs `xrdb -merge ~/.Xresources` at login keeps
//! the theme. `off` merges the values the server held before and removes the block; keys that did not exist stay in the running server
//! until the next `xrdb -load`.

use super::files::{Comment, Edit};
use super::{Config, Ctx, Env, Palette, Plan, Target};
use crate::theme::model::Rgb;
use serde_json::{json, Value};

pub struct X11;

/// ANSI colours 0..15 for terminals, from the palette.
pub fn ansi(p: &Palette) -> [Rgb; 16] {
    let br = |c| Palette::lighten(c, 0.2);
    let bright_fg = if p.dark { Palette::lighten(p.text, 0.5) } else { Rgb(0, 0, 0).over(p.text, 0.35) };
    [p.bg, p.red, p.green, p.yellow, p.blue, p.magenta, p.cyan, p.text, p.text_faint, br(p.red), br(p.green), br(p.yellow), br(p.blue), br(p.magenta), br(p.cyan), bright_fg]
}

/// `(resource, value)` pairs, in file order.
pub fn resources(p: &Palette, cfg: &Config) -> Vec<(String, String)> {
    let mut v = vec![
        ("*.foreground".to_string(), p.text.hex()),
        ("*.background".to_string(), p.bg.hex()),
        ("*.cursorColor".to_string(), p.text.hex()),
        ("*.highlightColor".to_string(), p.accent.hex()),
        ("*.highlightTextColor".to_string(), p.accent_text.hex()),
    ];
    for (i, c) in ansi(p).iter().enumerate() {
        v.push((format!("*.color{i}"), c.hex()));
    }
    if let Some(c) = &cfg.cursor_theme {
        v.push(("Xcursor.theme".into(), c.clone()));
    }
    v
}

pub fn file(p: &Palette, cfg: &Config) -> String {
    let mut s = format!("! {} ({}), generated by macthemectl\n", p.name, if p.dark { "dark" } else { "light" });
    for (k, v) in resources(p, cfg) {
        s.push_str(&format!("{k}: {v}\n"));
    }
    s
}

impl Target for X11 {
    fn id(&self) -> &'static str {
        "x11"
    }
    fn title(&self) -> &'static str {
        "X11 terminals"
    }
    fn detail(&self) -> &'static str {
        "Xresources for st, xterm and urxvt (merged with xrdb)"
    }
    fn available(&self, env: &Env) -> Result<(), String> {
        if env.has("xrdb") || env.home.join(".Xresources").exists() {
            Ok(())
        } else {
            Err("xrdb not installed".into())
        }
    }
    fn plan(&self, p: &Palette, cfg: &Config, env: &Env) -> Plan {
        let gen = env.gen_dir.join("Xresources");
        Plan {
            edits: vec![
                Edit::Whole { path: gen.clone(), text: file(p, cfg) },
                Edit::Block { path: env.home.join(".Xresources"), comment: Comment::Bang, text: format!("#include \"{}\"\n", gen.display()) },
            ],
            gsettings: Vec::new(),
        }
    }

    fn after(&self, cx: &mut Ctx) {
        if cx.env.display.is_none() || !cx.env.has("xrdb") {
            return;
        }
        let gen = cx.env.gen_dir.join("Xresources");
        let gen_s = gen.to_string_lossy().into_owned();
        let res = resources(cx.p, cx.cfg);
        let mut saved = cx.st.extra.get("xrdb").and_then(Value::as_object).cloned().unwrap_or_default();
        if saved.is_empty() {
            let q = cx.env.run.run("xrdb", &["-query"], &[]).stdout;
            for (k, _) in &res {
                let key = format!("{k}:");
                let old = q.lines().find_map(|l| l.strip_prefix(&key).map(|v| v.trim().to_string()));
                saved.insert(k.clone(), old.map_or(Value::Null, |o| json!(o)));
            }
            cx.st.extra.insert("xrdb".into(), Value::Object(saved));
        }
        let r = cx.env.run.run("xrdb", &["-merge", &gen_s], &[]);
        if !r.ok {
            cx.report.warnings.push(format!("xrdb -merge: {}", r.stderr.trim()));
        }
    }

    fn undo(&self, cx: &mut Ctx) {
        let Some(saved) = cx.st.extra.remove("xrdb").and_then(|v| v.as_object().cloned()) else { return };
        if cx.env.display.is_none() || !cx.env.has("xrdb") {
            return;
        }
        let text: String = saved.iter().filter_map(|(k, v)| v.as_str().map(|o| format!("{k}: {o}\n"))).collect();
        if text.is_empty() {
            return;
        }
        let f = cx.env.state_dir.join("xrdb-restore");
        if super::files::write_atomic(&f, &text).is_ok() {
            cx.env.run.run("xrdb", &["-merge", &f.to_string_lossy()], &[]);
            let _ = std::fs::remove_file(&f);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::super::testutil::*;
    use super::*;

    #[test]
    fn resource_file_golden_head() {
        let p = palette(true);
        let f = file(&p, &Config::default());
        let lines: Vec<&str> = f.lines().collect();
        assert_eq!(lines[0], "! macOS (dark), generated by macthemectl");
        assert_eq!(lines[1], format!("*.foreground: {}", p.text.hex()));
        assert_eq!(lines[2], format!("*.background: {}", p.bg.hex()));
        assert_eq!(f.matches("*.color").count(), 16);
        assert!(!f.contains("Xcursor"));
        assert!(file(&p, &Config { cursor_theme: Some("Bibata".into()), ..Config::default() }).contains("Xcursor.theme: Bibata"));
    }

    #[test]
    fn xrdb_merge_runs_only_with_a_display_and_restores_old_values() {
        let d = tmp("x11");
        let (mut env, fake) = env(&d, &["xrdb"]);
        env.display = Some(":92".into());
        fake.answers.borrow_mut().push(("xrdb -query".into(), "*.background:\t#101010\nXft.dpi:\t96\n".into()));
        let cfg = Config { enabled: true, ..Config::default() };
        let only = super::super::Opts { only: Some(vec!["x11".into()]), ..Default::default() };
        super::super::apply(&env, &cfg, &palette(true), &only).unwrap();
        let calls = fake.calls.borrow().clone();
        assert!(calls.iter().any(|c| c.starts_with("xrdb -merge ") && c.ends_with("macshell/system/Xresources")), "{calls:?}");
        assert!(std::fs::read_to_string(env.home.join(".Xresources")).unwrap().contains("#include \""));
        super::super::off(&env, &cfg, &palette(true)).unwrap();
        assert!(!env.home.join(".Xresources").exists(), "the file macshell created is gone");
        assert!(fake.calls.borrow().iter().filter(|c| c.starts_with("xrdb -merge ")).count() >= 2, "the old background is merged back");
    }
}
