/// The theme's name in Omarchy.
pub const THEME: &str = "decebal";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Kind {
    Core,
    Browser,
    Editors,
    Hooks,
}

pub struct Omarchy {
    kind: Kind,
}

impl Omarchy {
    pub fn new(kind: Kind) -> Omarchy {
        Omarchy { kind }
    }
}

/// `colors.toml` in Omarchy's format: the 16 ANSI colours and the semantic palette.
pub fn colors_toml(p: &Palette) -> String {
    let br = |c| Palette::lighten(c, 0.2);
    let a = x11::ansi(p);
    let black = Rgb(0, 0, 0);
    let (dark_bg, darker_bg) = if p.dark { (black.over(p.bg, 0.25), black.over(p.bg, 0.5)) } else { (p.text.over(p.bg, 0.05), p.text.over(p.bg, 0.1)) };
    let light_fg = if p.dark { Palette::lighten(p.text, 0.15) } else { black.over(p.text, 0.15) };
    let rows: Vec<(&str, String)> = vec![
        ("mode", format!("\"{}\"", if p.dark { "dark" } else { "light" })),
        ("", String::new()),
        ("accent", p.accent.hex()),
        ("selection", p.accent.over(p.bg, 0.35).hex()),
        ("muted", p.text_faint.hex()),
        ("", String::new()),
        ("background", p.bg.hex()),
        ("dark_background", dark_bg.hex()),
        ("darker_background", darker_bg.hex()),
        ("lighter_background", p.surface.hex()),
        ("", String::new()),
        ("foreground", p.text.hex()),
        ("dark_foreground", p.text_faint.hex()),
        ("light_foreground", light_fg.hex()),
        ("bright_foreground", a[15].hex()),
        ("", String::new()),
        ("red", p.red.hex()),
        ("yellow", p.yellow.hex()),
        ("orange", p.orange.hex()),
        ("green", p.green.hex()),
        ("cyan", p.cyan.hex()),
        ("blue", p.blue.hex()),
        ("magenta", p.magenta.hex()),
        ("brown", black.over(p.orange, 0.5).hex()),
        ("", String::new()),
        ("bright_red", br(p.red).hex()),
        ("bright_yellow", br(p.yellow).hex()),
        ("bright_green", br(p.green).hex()),
        ("bright_cyan", br(p.cyan).hex()),
        ("bright_blue", br(p.blue).hex()),
        ("bright_magenta", br(p.magenta).hex()),
    ];
    let mut s = format!("# {} ({}), generated by decthemectl from the decebal theme\n", p.name, if p.dark { "dark" } else { "light" });
    for (k, v) in rows {
        if k.is_empty() {
            s.push('\n');
        } else if k == "mode" {
            s.push_str(&format!("{k} = {v}\n"));
        } else {
            s.push_str(&format!("{k} = \"{v}\"\n"));
        }
    }
    s
}

fn theme_dir(env: &Env) -> PathBuf {
    env.config_home.join("omarchy/themes").join(THEME)
}

fn current_dir(env: &Env) -> PathBuf {
    env.state_home.join("omarchy/current")
}

fn current_name(env: &Env) -> Option<String> {
    std::fs::read_to_string(current_dir(env).join("theme.name")).ok().map(|s| s.trim().to_string()).filter(|s| !s.is_empty())
}

/// The environment Omarchy's scripts need: where Omarchy lives, no background change, no hooks and reload storms.
fn script_env(env: &Env) -> Vec<(String, String)> {
    let mut v = vec![("OMARCHY_THEME_HEADLESS".to_string(), "1".to_string()), ("OMARCHY_THEME_SKIP_BACKGROUND".to_string(), "1".to_string())];
    if let Some(p) = &env.omarchy_path {
        v.push(("OMARCHY_PATH".into(), p.to_string_lossy().into_owned()));
    }
    v
}

fn run(cx: &mut Ctx, cmd: &str, args: &[&str]) -> bool {
    if !cx.env.has(cmd) {
        return false;
    }
    let e = script_env(cx.env);
    let e: Vec<(&str, &str)> = e.iter().map(|(k, v)| (k.as_str(), v.as_str())).collect();
    let r = cx.env.run.run(cmd, args, &e);
    if !r.ok {
        cx.report.warnings.push(format!("{cmd} {}: {}", args.join(" "), r.stderr.trim().lines().last().unwrap_or("failed")));
    }
    r.ok
}

// pgrep's 1 means no matching process; other failures must remain visible.
// Recheck after a failed helper to tolerate btop exiting between probe and reload.
const BTOP_RELOAD: &str = r#"
pgrep -u "$1" -x btop >/dev/null
probe=$?
case "$probe" in 1) exit 0;; 0) ;; *) exit "$probe";; esac
omarchy-restart-btop
reload=$?
[ "$reload" -eq 0 ] && exit 0
pgrep -u "$1" -x btop >/dev/null
[ "$?" -eq 1 ] && exit 0
exit "$reload"
"#;

fn reload_btop(cx: &mut Ctx) {
    if !cx.env.has("btop") || !cx.env.has("omarchy-restart-btop") {
        return;
    }
    let uid = unsafe { libc::geteuid() }.to_string();
    let result = cx.env.run.run("sh", &["-c", BTOP_RELOAD, "decebal-btop-reload", &uid], &[]);
    if !result.ok {
        cx.report.warnings.push(format!("omarchy-restart-btop: {}", result.stderr.trim().lines().last().filter(|s| !s.is_empty()).unwrap_or("reload failed")));
    }
}

/// Sockets of kitty instances this user can address.
fn kitty_sockets(env: &Env) -> Vec<PathBuf> {
    let uid = unsafe { libc::geteuid() };
    let mut dirs: Vec<PathBuf> = vec![PathBuf::from("/tmp")];
    dirs.extend(env.runtime_dir.clone());
    let mut out = Vec::new();
    for d in dirs {
        for e in std::fs::read_dir(d).into_iter().flatten().flatten() {
            let name = e.file_name().to_string_lossy().into_owned();
            if !name.starts_with("kitty") {
                continue;
            }
            if let Ok(m) = e.metadata() {
                if m.file_type().is_socket() && m.uid() == uid {
                    out.push(e.path());
                }
            }
        }
    }
    out
}

/// Re-reads the terminals' colours. Nothing here signals a process: alacritty and foot are told through their own mechanisms,
/// kitty through its remote-control socket.
fn reload_terminals(cx: &mut Ctx) {
    let alacritty = cx.env.config_home.join("alacritty/alacritty.toml");
    if let Ok(f) = std::fs::OpenOptions::new().append(true).open(&alacritty) {
        let _ = f.set_modified(std::time::SystemTime::now());
        cx.report.notes.push("alacritty: config touched (it reloads itself)".into());
    }
    if cx.env.has("foot") {
        run(cx, "omarchy-theme-set-foot", &[]);
    }
    if cx.env.has("kitty") {
        let conf = current_dir(cx.env).join("theme/kitty.conf");
        for s in kitty_sockets(cx.env) {
            let to = format!("unix:{}", s.display());
            let r = cx.env.run.run("kitty", &["@", "--to", &to, "set-colors", "--all", "--configured", &conf.to_string_lossy()], &[]);
            if r.ok {
                cx.report.notes.push(format!("kitty: colours set on {}", s.display()));
            }
        }
    }
    if cx.cfg.signals {
        run(cx, "omarchy-restart-terminal", &[]);
        run(cx, "omarchy-restart-helix", &[]);
    }
}

/// Does sudo run Omarchy's browser policy helper without a password (so no prompt can appear)?
pub fn browser_passwordless(env: &Env) -> bool {
    if unsafe { libc::geteuid() } == 0 {
        return true;
    }
    env.has("sudo") && env.run.run("sudo", &["-n", "-l", "-l", "/usr/bin/omarchy-theme-set-browser-policy", "000000"], &[]).stdout.contains("!authenticate")
}

fn has_browser(env: &Env) -> bool {
    ["chromium", "google-chrome-stable", "google-chrome", "microsoft-edge-stable", "brave", "brave-browser"].iter().any(|b| env.has(b))
}

fn set_theme(cx: &mut Ctx, name: &str) -> bool {
    run(cx, "omarchy-theme-set", &[name])
}

/// The steps behind the sub-checkboxes, run after the theme is staged.
fn sub_steps(cx: &mut Ctx) {
    let core = Omarchy::new(Kind::Browser);
    if cx.cfg.is_on(&core, cx.env) && core.available(cx.env).is_ok() && browser_passwordless(cx.env) {
        run(cx, "omarchy-theme-set-browser", &[]);
    }
    let ed = Omarchy::new(Kind::Editors);
    if cx.cfg.is_on(&ed, cx.env) && ed.available(cx.env).is_ok() {
        run(cx, "omarchy-theme-set-vscode", &[]);
        run(cx, "omarchy-theme-set-obsidian", &[]);
    }
}

impl Target for Omarchy {
    fn id(&self) -> &'static str {
        match self.kind {
            Kind::Core => "omarchy",
            Kind::Browser => "browser",
            Kind::Editors => "editors",
            Kind::Hooks => "hooks",
        }
    }
    fn title(&self) -> &'static str {
        match self.kind {
            Kind::Core => "Terminals and Omarchy apps",
            Kind::Browser => "Browser colour",
            Kind::Editors => "Editors",
            Kind::Hooks => "Omarchy theme hooks",
        }
    }
    fn detail(&self) -> &'static str {
        match self.kind {
            Kind::Core => "alacritty, foot, kitty, ghostty, btop, helix, neovim through an Omarchy theme made from the palette",
            Kind::Browser => "Chromium / Chrome / Edge / Brave theme colour (needs Omarchy's passwordless browser rule)",
            Kind::Editors => "VS Code, Cursor and Obsidian (Omarchy's own sync; edits their settings)",
            Kind::Hooks => "Run the scripts in ~/.config/omarchy/hooks/theme-set.d",
        }
    }
    fn available(&self, env: &Env) -> Result<(), String> {
        if env.omarchy_path.is_none() || !env.has("omarchy-theme-set") {
            return Err("Omarchy not installed".into());
        }
        match self.kind {
            Kind::Core => Ok(()),
            Kind::Browser => {
                if !env.has("omarchy-theme-set-browser") {
                    Err("Omarchy has no browser helper".into())
                } else if !has_browser(env) {
                    Err("no Chromium-family browser installed".into())
                } else {
                    Ok(())
                }
            }
            Kind::Editors => {
                if ["code", "code-insiders", "codium", "cursor", "obsidian", "t3", "t3code", "pi", "claude", "hermes"].iter().any(|c| env.has(c)) {
                    Ok(())
                } else {
                    Err("no supported editor or coding app installed".into())
                }
            }
            Kind::Hooks => {
                if env.config_home.join("omarchy/hooks/theme-set").exists() || env.config_home.join("omarchy/hooks/theme-set.d").is_dir() {
                    Ok(())
                } else {
                    Err("no theme-set hook".into())
                }
            }
        }
    }
    fn default_on(&self, env: &Env) -> bool {
        match self.kind {
            Kind::Core => self.available(env).is_ok(),
            Kind::Browser => self.available(env).is_ok() && browser_passwordless(env),
            Kind::Editors => self.available(env).is_ok(),
            Kind::Hooks => false,
        }
    }

    fn plan(&self, p: &Palette, _cfg: &Config, env: &Env) -> Plan {
        match self.kind {
            Kind::Core => Plan { edits: vec![Edit::Whole { path: theme_dir(env).join("colors.toml"), text: colors_toml(p) }], gsettings: Vec::new() },
            _ => Plan::default(),
        }
    }

    fn after(&self, cx: &mut Ctx) {
        match self.kind {
            Kind::Core => {
                let name = current_name(cx.env);
                if name.as_deref() != Some(THEME) && !cx.st.extra.contains_key("omarchyPrev") {
                    cx.st.extra.insert("omarchyPrev".into(), json!(name));
                }
                let written = cx.report.wrote.iter().any(|w| w.starts_with(theme_dir(cx.env)));
                if !written && name.as_deref() == Some(THEME) {
                    return; // already staged with this palette
                }
                if !set_theme(cx, THEME) {
                    return;
                }
                reload_terminals(cx);
                reload_btop(cx);
            }
            Kind::Browser => {
                if browser_passwordless(cx.env) {
                    run(cx, "omarchy-theme-set-browser", &[]);
                } else {
                    cx.report.warnings.push("Browser theme was not applied: Omarchy's passwordless browser policy rule is unavailable".into());
                }
            }
            Kind::Editors => {
                for helper in ["omarchy-theme-set-vscode", "omarchy-theme-set-obsidian", "omarchy-theme-set-t3code", "omarchy-theme-set-pi", "omarchy-theme-set-claude", "omarchy-theme-set-hermes"] {
                    run(cx, helper, &[]);
                }
            }
            Kind::Hooks => {
                let written = cx.report.wrote.iter().any(|w| w.starts_with(theme_dir(cx.env)));
                if written {
                    run(cx, "omarchy-hook", &["theme-set", THEME]);
                }
            }
        }
    }

    fn undo(&self, cx: &mut Ctx) {
        if self.kind != Kind::Core {
            return;
        }
        let prev = cx.st.extra.remove("omarchyPrev").and_then(|v| v.as_str().map(String::from));
        let staged = current_name(cx.env).as_deref() == Some(THEME);
        match (prev, staged) {
            (Some(prev), true) => {
                if cx.env.omarchy_path.as_ref().is_some_and(|o| o.join("themes").join(&prev).is_dir()) || cx.env.config_home.join("omarchy/themes").join(&prev).is_dir() {
                    if set_theme(cx, &prev) {
                        reload_terminals(cx);
                        reload_btop(cx);
                        sub_steps(cx);
                        if cx.cfg.is_on(&Omarchy::new(Kind::Hooks), cx.env) && Omarchy::new(Kind::Hooks).available(cx.env).is_ok() {
                            run(cx, "omarchy-hook", &["theme-set", &prev]);
                        }
                    }
                } else {
                    cx.report.warnings.push(format!("Omarchy theme `{prev}` no longer exists; the Omarchy theme decebal set stays current"));
                }
            }
            (None, true) => cx.report.notes.push("Omarchy had no theme before decebal; the colours stay until you pick one (`omarchy theme set`)".into()),
            _ => {}
        }
    }
}

