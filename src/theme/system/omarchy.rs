//! The Omarchy bridge: terminals, btop, helix, neovim, editors and the browser colour, by way of Omarchy's own machinery.
//!
//! decebal writes one thing: `~/.config/omarchy/themes/decebal/colors.toml`, the palette in Omarchy's format. Omarchy's
//! `omarchy-theme-set` then stages the theme and its template engine (`omarchy-theme-set-templates`, the `*.tpl` files under
//! `$OMARCHY_PATH/default/themed` plus the user's `~/.config/omarchy/themed`) makes alacritty.toml, kitty.conf, foot.ini, ghostty.conf,
//! btop.theme, helix.toml, neovim.lua, vscode-theme.json, obsidian.css, chromium.theme, ... exactly as for any shipped theme, so nothing
//! is reimplemented here.
//!
//! `omarchy-theme-set` runs in its headless mode with the background step off (decebal owns the wallpaper), and the reload steps that
//! follow are run one by one, each behind its own checkbox:
//!
//! * `omarchy` (core): the theme itself, terminals (alacritty: its config is touched, it watches it; foot: Omarchy's OSC helper;
//!   kitty: `kitty @ set-colors` on sockets that exist), btop (Omarchy's `omarchy-restart-btop`). No signal is sent to any other
//!   process unless the `signals` option is set.
//! * `browser`: `omarchy-theme-set-browser` (the Chromium / Chrome / Edge / Brave theme colour, written to the managed policy directory
//!   through sudo/pkexec). Only used when sudo would not ask for a password; otherwise the box is off by default.
//! * `editors`: `omarchy-theme-set-vscode` and `omarchy-theme-set-obsidian`.
//! * `hooks`: the user's `~/.config/omarchy/hooks/theme-set.d`.
//!
//! `off` runs `omarchy-theme-set` for the theme that was current before decebal took over.

