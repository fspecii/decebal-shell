//! Settings that must be applied again at every login (keyboard, pointer, screen blanking, cursor size ...).
//!
//! Source of truth: `~/.config/decebal/session-settings.json`. From it decsettings generates
//! `~/.config/decebal/session-settings.sh`, a POSIX shell snippet that the login session sources
//! (`[ -r "$f" ] && . "$f"`). Every command in it is guarded, so a missing tool or a missing X server is harmless.

use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};

#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct XinputSet {
    pub device: String,
    pub prop: String,
    pub value: String,
}

#[derive(Debug, Clone, PartialEq, Default, Serialize, Deserialize)]
#[serde(default)]
pub struct Session {
    pub kbd_layout: Option<String>,
    pub kbd_variant: Option<String>,
    pub kbd_options: Vec<String>,
    pub repeat_delay: Option<u32>,
    pub repeat_rate: Option<u32>,
    pub xinput: Vec<XinputSet>,
    /// Screen saver / blank timeout in seconds (0 = never).
    pub blank_secs: Option<u32>,
    /// DPMS off timeout in seconds (0 = DPMS disabled).
    pub dpms_secs: Option<u32>,
    pub cursor_size: Option<u32>,
    pub xft_dpi: Option<u32>,
    /// Command name exported as `RDWM_TERMINAL` (read by `rdwm-terminal`).
    pub terminal: Option<String>,
    pub reduce_motion: bool,
    pub font_scale: Option<f32>,
    pub high_contrast: bool,
    /// Screen lock command / idle seconds / lock before suspend (exported as DECEBAL_LOCK_*).
    pub lock_cmd: Option<String>,
    pub lock_secs: Option<u32>,
    pub lock_on_suspend: bool,
    /// `xrandr` arguments of the last confirmed display layout.
    pub xrandr: Vec<String>,
    /// Night shift: (tool, kelvin). `None` = off.
    pub night: Option<(String, u32)>,
}

pub fn config_home() -> PathBuf {
    std::env::var_os("XDG_CONFIG_HOME")
        .filter(|s| !s.is_empty())
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")))
        .unwrap_or_else(|| PathBuf::from("."))
}

pub fn dir() -> PathBuf {
    config_home().join("decebal")
}

impl Session {
    pub fn json_path(dir: &Path) -> PathBuf {
        dir.join("session-settings.json")
    }
    pub fn sh_path(dir: &Path) -> PathBuf {
        dir.join("session-settings.sh")
    }

    pub fn load(dir: &Path) -> Session {
        std::fs::read_to_string(Self::json_path(dir)).ok().and_then(|t| serde_json::from_str(&t).ok()).unwrap_or_default()
    }

    /// Writes both files atomically (temp + rename). Errors are returned as text.
    pub fn save(&self, dir: &Path) -> Result<(), String> {
        std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;
        let json = serde_json::to_string_pretty(self).map_err(|e| e.to_string())?;
        write_atomic(&Self::json_path(dir), &(json + "\n"))?;
        let sh = self.to_sh();
        write_atomic(&Self::sh_path(dir), &sh)?;
        // The session script of the pre-rename release still sources ~/.config/macshell/session-settings.sh: keep that file
        // current while it exists (best effort; remove it once the session script reads the new folder).
        if let Some(old) = dir.parent().map(|p| p.join("macshell")).filter(|_| dir.file_name().is_some_and(|n| n == "decebal")) {
            if Self::sh_path(&old).is_file() {
                let _ = write_atomic(&Self::sh_path(&old), &sh);
            }
        }
        Ok(())
    }

    pub fn to_sh(&self) -> String {
        let mut s = String::from(
            "# Generated by decsettings (System Settings). Do not edit: change the settings there, or edit\n\
             # session-settings.json next to this file. Source it from the login session:\n\
             #   [ -r \"${XDG_CONFIG_HOME:-$HOME/.config}/decebal/session-settings.sh\" ] && . \"${XDG_CONFIG_HOME:-$HOME/.config}/decebal/session-settings.sh\"\n\
             have() { command -v \"$1\" >/dev/null 2>&1; }\n",
        );
        if let Some(t) = &self.terminal {
            s += &format!("export RDWM_TERMINAL={}\n", q(t));
        }
        if let Some(c) = self.cursor_size {
            s += &format!("export XCURSOR_SIZE={c}\n");
        }
        if self.reduce_motion {
            s += "export DECEBAL_REDUCE_MOTION=1\n";
        }
        if self.high_contrast {
            s += "export DECEBAL_HIGH_CONTRAST=1\n";
        }
        if let Some(c) = &self.lock_cmd {
            s += &format!("export DECEBAL_LOCK_CMD={}\n", q(c));
        }
        if let Some(n) = self.lock_secs {
            s += &format!("export DECEBAL_LOCK_SECS={n}\n");
        }
        if self.lock_on_suspend {
            s += "export DECEBAL_LOCK_ON_SUSPEND=1\n";
        }
        if let Some(f) = self.font_scale {
            s += &format!("export DECEBAL_FONT_SCALE={f:.2}\n");
        }
        s += "if [ -n \"$DISPLAY\" ]; then\n";
        if !self.xrandr.is_empty() {
            s += &format!("  have xrandr && xrandr {}\n", self.xrandr.iter().map(|a| q(a)).collect::<Vec<_>>().join(" "));
        }
        if self.kbd_layout.is_some() || !self.kbd_options.is_empty() {
            let mut c = String::from("  have setxkbmap && setxkbmap");
            if let Some(l) = &self.kbd_layout {
                c += &format!(" -layout {}", q(l));
                c += &format!(" -variant {}", q(self.kbd_variant.as_deref().unwrap_or("")));
            }
            c += " -option";
            for o in &self.kbd_options {
                c += &format!(" -option {}", q(o));
            }
            s += &c;
            s += "\n";
        }
        if let (Some(d), Some(r)) = (self.repeat_delay, self.repeat_rate) {
            s += &format!("  have xset && xset r rate {d} {r}\n");
        }
        for x in &self.xinput {
            s += &format!("  have xinput && xinput --set-prop {} {} {} 2>/dev/null\n", q(&x.device), q(&x.prop), x.value.split(' ').map(q).collect::<Vec<_>>().join(" "));
        }
        if let Some(b) = self.blank_secs {
            s += &format!("  have xset && xset s {b} {b}\n");
            if b == 0 {
                s += "  have xset && xset s off\n";
            }
        }
        if let Some(d) = self.dpms_secs {
            if d == 0 {
                s += "  have xset && xset -dpms\n";
            } else {
                s += &format!("  have xset && xset +dpms dpms {d} {d} {d}\n");
            }
        }
        let mut xrdb = String::new();
        if let Some(c) = self.cursor_size {
            xrdb += &format!("Xcursor.size: {c}\\n");
        }
        if let Some(d) = self.xft_dpi {
            xrdb += &format!("Xft.dpi: {d}\\n");
        }
        if !xrdb.is_empty() {
            s += &format!("  have xrdb && printf '{xrdb}' | xrdb -merge\n");
        }
        if let Some((tool, k)) = &self.night {
            let flags = "-P -O";
            s += &format!("  have {} && {} {flags} {k} >/dev/null 2>&1\n", q(tool), q(tool));
        }
        s += "fi\n";
        s
    }
}

/// Single-quote for POSIX sh.
pub fn q(v: &str) -> String {
    if !v.is_empty() && v.chars().all(|c| c.is_ascii_alphanumeric() || "-_.,:/+=@%".contains(c)) {
        return v.to_string();
    }
    format!("'{}'", v.replace('\'', "'\\''"))
}

pub fn write_atomic(path: &Path, text: &str) -> Result<(), String> {
    let tmp = path.with_extension(format!("tmp{}", std::process::id()));
    std::fs::write(&tmp, text).map_err(|e| format!("{}: {e}", tmp.display()))?;
    std::fs::rename(&tmp, path).map_err(|e| {
        let _ = std::fs::remove_file(&tmp);
        format!("{}: {e}", path.display())
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn quoting() {
        assert_eq!(q("us"), "us");
        assert_eq!(q("ctrl:nocaps"), "ctrl:nocaps");
        assert_eq!(q("Logitech MX Master"), "'Logitech MX Master'");
        assert_eq!(q("it's"), "'it'\\''s'");
        assert_eq!(q(""), "''");
    }

    #[test]
    fn empty_session_is_harmless() {
        let s = Session::default().to_sh();
        assert!(s.contains("have()"));
        assert!(!s.contains("setxkbmap"));
        assert!(s.contains("fi\n"));
    }

    #[test]
    fn full_session_generates_every_command() {
        let s = Session {
            kbd_layout: Some("us".into()),
            kbd_variant: Some("".into()),
            kbd_options: vec!["ctrl:nocaps".into(), "compose:ralt".into()],
            repeat_delay: Some(250),
            repeat_rate: Some(40),
            xinput: vec![XinputSet { device: "Logitech MX".into(), prop: "libinput Accel Speed".into(), value: "0.5".into() }],
            blank_secs: Some(600),
            dpms_secs: Some(900),
            cursor_size: Some(32),
            xft_dpi: Some(120),
            terminal: Some("alacritty".into()),
            reduce_motion: true,
            font_scale: Some(1.25),
            high_contrast: false,
            lock_cmd: Some("hyprlock".into()),
            lock_secs: Some(300),
            lock_on_suspend: true,
            xrandr: vec!["--output".into(), "DP-1".into(), "--mode".into(), "1920x1080".into()],
            night: Some(("redshift".into(), 4000)),
        };
        let t = s.to_sh();
        assert!(t.contains("export RDWM_TERMINAL=alacritty\n"));
        assert!(t.contains("export XCURSOR_SIZE=32\n"));
        assert!(t.contains("export DECEBAL_REDUCE_MOTION=1\n"));
        assert!(t.contains("export DECEBAL_FONT_SCALE=1.25\n"));
        assert!(t.contains("export DECEBAL_LOCK_CMD=hyprlock\n") && t.contains("export DECEBAL_LOCK_SECS=300\n") && t.contains("export DECEBAL_LOCK_ON_SUSPEND=1\n"));
        assert!(t.contains("xrandr --output DP-1 --mode 1920x1080\n"));
        assert!(t.contains("setxkbmap -layout us -variant '' -option -option ctrl:nocaps -option compose:ralt\n"));
        assert!(t.contains("xset r rate 250 40\n"));
        assert!(t.contains("xinput --set-prop 'Logitech MX' 'libinput Accel Speed' 0.5 2>/dev/null\n"));
        assert!(t.contains("xset s 600 600\n"));
        assert!(t.contains("xset +dpms dpms 900 900 900\n"));
        assert!(t.contains("Xcursor.size: 32\\nXft.dpi: 120\\n"));
        assert!(t.contains("redshift -P -O 4000"));
    }

    #[test]
    fn json_roundtrip_and_save() {
        let d = std::env::temp_dir().join(format!("ms-sess-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        let s = Session { repeat_delay: Some(300), repeat_rate: Some(30), ..Session::default() };
        s.save(&d).unwrap();
        assert_eq!(Session::load(&d), s);
        assert!(std::fs::read_to_string(Session::sh_path(&d)).unwrap().contains("xset r rate 300 30"));
        // a corrupt file loads as defaults, never panics
        std::fs::write(Session::json_path(&d), "{nope").unwrap();
        assert_eq!(Session::load(&d), Session::default());
        let _ = std::fs::remove_dir_all(&d);
    }
}
